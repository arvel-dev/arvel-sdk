package fakevendor

import (
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strconv"
	"sync"

	"gopkg.in/yaml.v3"
)

// Build compiles a temporary self-contained executable named name that replays
// s, using `go build`. It returns the absolute path and a cleanup func.
func Build(ctx context.Context, s *Script, name string) (string, func(), error) {
	dir, err := os.MkdirTemp("", "fakevendor-*")
	if err != nil {
		return "", nil, err
	}
	cleanup := func() { _ = os.RemoveAll(dir) }
	fail := func(err error) (string, func(), error) {
		cleanup()
		return "", nil, err
	}

	data, err := yaml.Marshal(s)
	if err != nil {
		return fail(err)
	}

	src := "// Code generated by testkit/fakevendor.Build. DO NOT EDIT.\n" +
		"package main\n\n" +
		"import (\n" +
		"\t\"context\"\n" +
		"\t\"fmt\"\n" +
		"\t\"os\"\n" +
		"\t\"strings\"\n\n" +
		"\t\"github.com/arvel-dev/arvel-sdk/testkit/fakevendor\"\n" +
		")\n\n" +
		"const script = " + strconv.Quote(string(data)) + "\n\n" +
		"func main() {\n" +
		"\ts, err := fakevendor.Load(strings.NewReader(script))\n" +
		"\tif err != nil {\n" +
		"\t\tfmt.Fprintln(os.Stderr, err)\n" +
		"\t\tos.Exit(2)\n" +
		"\t}\n" +
		"\tos.Exit(fakevendor.Run(context.Background(), s, os.Args[1:], os.Stdin, os.Stdout, os.Stderr))\n" +
		"}\n"

	if err := os.WriteFile(filepath.Join(dir, "main.go"), []byte(src), 0o644); err != nil {
		return fail(err)
	}

	gomod := "module fakevendor.local\n\ngo 1.27.2\n\n" +
		"require github.com/arvel-dev/arvel-sdk v0.0.0\n\n" +
		"replace github.com/arvel-dev/arvel-sdk => " + moduleRoot() + "\n"
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte(gomod), 0o644); err != nil {
		return fail(err)
	}

	out := filepath.Join(dir, name)
	cmd := exec.CommandContext(ctx, "go", "build", "-mod=mod", "-o", out, ".")
	cmd.Dir = dir
	if b, err := cmd.CombinedOutput(); err != nil {
		return fail(fmt.Errorf("fakevendor: go build: %w\n%s", err, b))
	}
	return out, cleanup, nil
}

var (
	moduleRootOnce sync.Once
	moduleRootPath string
)

// moduleRoot returns the absolute repository root by walking up from this file
// to the nearest go.mod.
func moduleRoot() string {
	moduleRootOnce.Do(func() {
		_, file, _, _ := runtime.Caller(0)
		dir := filepath.Dir(file)
		for {
			if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
				moduleRootPath = dir
				return
			}
			parent := filepath.Dir(dir)
			if parent == dir {
				moduleRootPath = dir
				return
			}
			dir = parent
		}
	})
	return moduleRootPath
}
